"""Generate two audio-aware DUOVEX charts for Light It Up.

Requires Python 3, NumPy, SciPy and FFmpeg *only when regenerating*. The two
JSONs generated by this tool require no Python packages at Unity runtime.

128 BPM / first on-grid beat 7.412 s are validated against low/mid/high-band
transient envelopes of the bundled recording. Patterns follow 4-bar phrases;
offbeat and sixteenth-note accents are chosen from measured attacks, not RNG.
"""
from __future__ import annotations

import json
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from scipy.ndimage import gaussian_filter1d
from scipy.signal import stft

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "Assets/Resources/Tracks/LightItUp.mp3"
CHARTS = ROOT / "Assets/Resources/Charts"
BPM = 128.0
OFFSET_MS = 7412.0
BEAT_SECONDS = 60 / BPM
LAST_BEAT = 374

# Time-coded from the supplied recording; boundaries are whole musical bars.
SECTIONS = (
    (0, 8, "intro"),
    (8, 16, "verse"),
    (16, 24, "build"),
    (24, 40, "drop"),
    (40, 44, "break"),
    (44, 60, "verse2"),
    (60, 68, "build2"),
    (68, 92, "drop2"),
    (92, 94, "outro"),
)


class Transients:
    def __init__(self):
        pcm = subprocess.check_output(
            ["ffmpeg", "-nostdin", "-v", "error", "-i", str(AUDIO),
             "-f", "f32le", "-ar", "11025", "-ac", "1", "pipe:1"]
        )
        audio = np.frombuffer(pcm, dtype="<f4")
        self.duration = len(audio) / 11025
        freqs, times, stft_data = stft(
            audio, fs=11025, nperseg=1024, noverlap=768, boundary=None
        )
        # Positive changes in log spectral energy accentuate actual attacks
        # and avoid creating a note on every sustained pad/synth peak.
        spectral_flux = np.maximum(
            0, np.diff(np.log1p(np.abs(stft_data) * 120), axis=1)
        )
        self.times = times[1:]
        self.envelopes = {}
        for name, lo, hi in (("kick", 45, 200), ("body", 200, 2000),
                             ("hat", 2000, 5100)):
            band = spectral_flux[(freqs >= lo) & (freqs < hi)].mean(axis=0)
            band = gaussian_filter1d(band, 0.65)
            reference = np.percentile(band[(self.times > 22) &
                                           (self.times < 178)], 75)
            self.envelopes[name] = band / max(1e-7, reference)

    def bands(self, beat):
        timestamp = OFFSET_MS / 1000 + beat * BEAT_SECONDS
        if timestamp >= self.duration - 0.2:
            return (0.0, 0.0, 0.0)
        # A 35 ms tolerance captures attacks a few milliseconds around a
        # quantized 128 BPM gridline without shifting note timing off-grid.
        indices = np.flatnonzero(
            (self.times >= timestamp - .025) &
            (self.times <= timestamp + .025)
        )
        if not len(indices):
            indices = [int(np.argmin(np.abs(self.times - timestamp)))]
        return tuple(float(self.envelopes[n][indices].max())
                     for n in ("kick", "body", "hat"))

    def accent(self, beat, preference="all"):
        kick, body, hat = self.bands(beat)
        if preference == "hat":
            return 0.25 * kick + .45 * body + 1.5 * hat
        return 1.2 * kick + .95 * body + .78 * hat


def phrase(bar):
    return next(label for start, end, label in SECTIONS if start <= bar < end)


class Chart:
    def __init__(self, name, transients):
        self.name = name
        self.audio = transients
        self.notes = {}
        self.holds = []

    def add(self, beat, key, duration=0):
        beat = round(beat * 4) / 4
        assert beat >= 0 and 0 <= key <= 3 and duration >= 0
        identity = (beat, key)
        if identity in self.notes:
            return False
        if any(hkey == key and hstart < beat < hstart + length
               for hstart, hkey, length in self.holds):
            return False
        if duration and any(nkey == key and beat < nbeat < beat + duration
                            for nbeat, nkey in self.notes):
            return False
        self.notes[identity] = duration
        if duration:
            self.holds.append((beat, key, duration))
        return True

    def dual(self, beat):
        self.add(beat, 1)
        self.add(beat, 2)

    def outer(self, beat):
        self.add(beat, 0)
        self.add(beat, 3)

    def choose(self, bar, positions, count, preference="all"):
        # Choose the strongest measured transient positions within this bar.
        ranked = sorted(positions, key=lambda p: (
            -self.audio.accent(bar * 4 + p, preference), p))
        return sorted(ranked[:count])

    def serialize(self, filename, title):
        ordered = sorted(self.notes.items())
        obj = {
            "schemaVersion": 1,
            "title": title,
            "bpm": BPM,
            "offsetMs": OFFSET_MS,
            "tickDivision": 4,
            "notes": [
                {"id": idx, "beat": float(beat), "input": key,
                 "durationBeats": float(length)}
                for idx, ((beat, key), length) in enumerate(ordered, 1)
            ],
        }
        filename.write_text(json.dumps(obj, ensure_ascii=False, indent=2) +
                            "\n", encoding="utf-8")
        return obj


def base_key(bar, pos, style):
    """Four-key mirrored call/response: outer kick, inner snare."""
    flip = (bar // 2) % 2
    if pos == 0:
        return 0 if flip == 0 else 3
    if pos == 1:
        return 2 if flip == 0 else 1
    if pos == 2:
        return 3 if flip == 0 else 0
    if pos == 3:
        return 1 if flip == 0 else 2
    # Eighths emphasize the shared lane, with occasional outer echoes.
    ix = int(pos * 2) % 4
    return ([1, 2, 1, 3] if (bar + (style == "drop2")) % 2
            else [2, 1, 2, 0])[ix]


def make_chart(difficulty, audio):
    hard = difficulty == "HARD"
    chart = Chart(difficulty, audio)
    for start, end, style in SECTIONS:
        for bar in range(start, end):
            beat0 = bar * 4
            local = bar - start
            if style == "break":
                # The 01:22 breakdown has genuine sustained notes; keep this
                # calmer so the ensuing 01:30 verse feels like a new phrase.
                if local % 2 == 0:
                    key = 1 if local == 0 else 2
                    chart.add(beat0, key, 3.5 if not hard else 3.0)
                    chart.add(beat0 + 2, 3 if key == 1 else 0)
                else:
                    chart.add(beat0, 0 if local == 1 else 3, 3)
                    chart.add(beat0 + 2, 2 if local == 1 else 1)
                if hard:
                    for pos in chart.choose(bar, [.5, 1.5, 2.5, 3.5], 2, "hat"):
                        chart.add(beat0 + pos, 3 if local % 2 else 0)
                continue

            if style == "outro":
                if local == 0:
                    if hard:
                        chart.dual(beat0)
                        chart.add(beat0 + 1, 0)
                    else:
                        chart.add(beat0, 0)
                    chart.add(beat0 + 2, 3)
                else:
                    chart.outer(beat0)
                    chart.dual(beat0 + 1)
                    chart.add(beat0 + 2, 0, 2)
                    chart.add(beat0 + 2, 3, 2)
                continue

            if style == "intro":
                main = [0, 2] if not hard else [0, 1, 2, 3]
                half_count = 0 if not hard else 1
            elif style in ("verse", "verse2"):
                main = [0, 1, 2, 3] if hard or bar % 2 == 0 else [0, 2, 3]
                half_count = 0 if not hard else 2
            elif style in ("build", "build2"):
                main = [0, 1, 2, 3]
                half_count = (1 if local < 4 else 2) if not hard else (
                    2 if local < 4 else 4)
            elif style == "drop":
                main = [0, 1, 2, 3]
                half_count = 2 if not hard else 4
            else:  # drop2, biggest refrain
                main = [0, 1, 2, 3]
                half_count = 2 if not hard else 4

            for pos in main:
                beat = beat0 + pos
                # Strong musical downbeats get playable two-hand accents.
                if hard and style.startswith("drop") and pos == 0 and local % 2 == 0:
                    if local % 4 == 0:
                        chart.dual(beat)
                    else:
                        chart.outer(beat)
                elif not hard and style.startswith("drop") and pos == 0 and local % 4 == 0:
                    chart.dual(beat)
                elif hard and style in ("build", "build2") and pos == 0 and local == end-start-1:
                    chart.dual(beat)
                else:
                    chart.add(beat, base_key(bar, pos, style))

            eighths = chart.choose(bar, [.5, 1.5, 2.5, 3.5], half_count, "hat")
            for pos in eighths:
                beat = beat0 + pos
                key = base_key(bar, pos, style)
                # Audible 8th-note repetitions alternate with F/J exchanges.
                if hard and style.startswith("drop") and (
                    (bar + int(pos * 2)) % 5 == 0):
                    key = base_key(bar, int(pos), style)
                chart.add(beat, key)

            if hard and style in ("build", "build2", "drop", "drop2"):
                # Sixteenths (117 ms spacing) are placed only at strong
                # recorded high-frequency attacks, especially phrase fills.
                count = 2 if (local + 1) % 4 == 0 else (
                    1 if style == "drop2" and bar % 2 == 0 else 0)
                if count:
                    candidates = [.25, .75, 1.25, 1.75, 2.25, 2.75, 3.25, 3.75]
                    for pos in chart.choose(bar, candidates, count, "hat"):
                        key = base_key(bar, int(pos), style)
                        # One quarter -> sixteenth -> eighth run at a time.
                        chart.add(beat0 + pos, key)

            if hard and style.startswith("drop") and local % 4 == 2:
                # Additional whole-lane chord on the 3rd beat, if no note is
                # already attached to one of these keys.
                chart.add(beat0 + 2, 0)
                chart.add(beat0 + 2, 3)

    return chart


def describe(chart):
    beats = defaultdict(list)
    for (beat, key), duration in chart.notes.items():
        beats[beat].append(key)
    shared_duals = sum(1 for keys in beats.values() if 1 in keys and 2 in keys)
    chords = sum(1 for keys in beats.values() if len(keys) >= 2)
    return {
        "notes": len(chart.notes),
        "maxChord": max(len(keys) for keys in beats.values()),
        "chords": chords, "dual": shared_duals,
        "holds": sum(duration > 0 for duration in chart.notes.values()),
        "inputs": dict(Counter(key for _, key in chart.notes)),
        "sixteenths": sum(int(beat * 4) % 2 for beat, _ in chart.notes),
    }


if __name__ == "__main__":
    assert AUDIO.is_file(), AUDIO
    transients = Transients()
    CHARTS.mkdir(parents=True, exist_ok=True)
    print(f"audio length: {transients.duration:.3f}s, BPM {BPM}, offset {OFFSET_MS}ms")
    for difficulty in ("NORMAL", "HARD"):
        chart = make_chart(difficulty, transients)
        output = CHARTS / f"LightItUp{difficulty.title()}.json"
        chart.serialize(output, f"LIGHT IT UP / {difficulty}")
        print(output.name, describe(chart))
